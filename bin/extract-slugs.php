<?php
/**
 * Extract registered ACF layout slugs + field names into the slug registry.
 *
 * Usage:
 *   php bin/extract-slugs.php --write   Regenerate docs/contracts/slug-registry.json
 *   php bin/extract-slugs.php --check   Exit 1 if the committed registry is stale
 *
 * Loads inc/fields/*.php under WP/ACF shims, captures every
 * acf_add_local_field_group() call, and walks the field tree collecting
 * field names, Flexible Content layout slugs and each field's storage path
 * (FLEET07).
 *
 * @package Salt\Tooling
 */

declare(strict_types=1);

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

$salt_root = dirname( __DIR__ );

require $salt_root . '/tests/wp-shims.php';

/** Captured field groups. @var array<int,array<string,mixed>> */
$GLOBALS['salt_captured_groups'] = array();

if ( ! function_exists( 'acf_add_local_field_group' ) ) {
	/**
	 * ACF shim: capture the group definition.
	 *
	 * @param array<string,mixed> $field_group Field group array.
	 * @return void
	 */
	function acf_add_local_field_group( array $field_group ): void {
		$GLOBALS['salt_captured_groups'][] = $field_group;
	}
}

if ( ! function_exists( 'salt_log' ) ) {
	/**
	 * Log shim for the extractor context.
	 *
	 * @param string $message Log line.
	 * @return void
	 */
	function salt_log( string $message ): void {
		fwrite( STDERR, 'salt: ' . $message . "\n" );
	}
}

// Foundation modules field registration depends on, then the field modules,
// then fire the hooks registration runs on.
require_once $salt_root . '/inc/helpers.php';
require_once $salt_root . '/inc/modules.php';
require_once $salt_root . '/inc/acf.php';
require_once $salt_root . '/inc/query/resolver.php';

$salt_fields_files = glob( $salt_root . '/inc/fields/*.php' );
foreach ( false === $salt_fields_files ? array() : $salt_fields_files as $salt_fields_file ) {
	require_once $salt_fields_file;
}
salt_test_do_action( 'acf/init' );
salt_test_do_action( 'init' );

/**
 * Recursively collect field names and FC layout slugs from a field list.
 *
 * @param array<int,array<string,mixed>> $fields  Field definitions.
 * @param string[]                       $names   Collected field names (by ref).
 * @param string[]                       $layouts Collected layout slugs (by ref).
 * @return void
 */
function salt_collect_slugs( array $fields, array &$names, array &$layouts ): void {
	foreach ( $fields as $field ) {
		if ( isset( $field['name'] ) && '' !== $field['name'] ) {
			$names[] = (string) $field['name'];
		}
		if ( isset( $field['sub_fields'] ) && is_array( $field['sub_fields'] ) ) {
			salt_collect_slugs( $field['sub_fields'], $names, $layouts );
		}
		if ( isset( $field['layouts'] ) && is_array( $field['layouts'] ) ) {
			foreach ( $field['layouts'] as $layout ) {
				if ( isset( $layout['name'] ) ) {
					$layouts[] = (string) $layout['name'];
				}
				if ( isset( $layout['sub_fields'] ) && is_array( $layout['sub_fields'] ) ) {
					salt_collect_slugs( $layout['sub_fields'], $names, $layouts );
				}
			}
		}
	}
}

/**
 * Recursively collect storage paths as ACF builds meta keys: each enclosing
 * group, repeater or Flexible Content name, then the field name, joined by
 * `_`, with a repeater or Flexible Content row written as N. Paths sit under
 * a scope: the group key, then ` / layout` for each layout they live in.
 *
 * @param array<int,array<string,mixed>> $fields Field definitions.
 * @param string                         $prefix Path so far ('' at a group's top).
 * @param string                         $scope  Group key, plus ` / layout` inside a layout.
 * @param array<string,string[]>         $paths  Collected paths by scope (by ref).
 * @return void
 */
function salt_collect_paths( array $fields, string $prefix, string $scope, array &$paths ): void {
	foreach ( $fields as $field ) {
		$name = (string) ( $field['name'] ?? '' );
		if ( '' === $name ) {
			continue; // A tab or message stores nothing.
		}
		$path              = '' === $prefix ? $name : $prefix . '_' . $name;
		$paths[ $scope ][] = $path;
		$type              = (string) ( $field['type'] ?? '' );
		if ( 'flexible_content' === $type ) {
			foreach ( (array) ( $field['layouts'] ?? array() ) as $layout ) {
				salt_collect_paths( (array) ( $layout['sub_fields'] ?? array() ), $path . '_N', $scope . ' / ' . (string) ( $layout['name'] ?? '' ), $paths );
			}
		} elseif ( isset( $field['sub_fields'] ) && is_array( $field['sub_fields'] ) ) {
			salt_collect_paths( $field['sub_fields'], 'repeater' === $type ? $path . '_N' : $path, $scope, $paths );
		}
	}
}

$salt_registry = array(
	'_readme' => 'Generated by `php bin/extract-slugs.php --write`. Do not edit by hand. FLEET07: this registry is the machine-checked contract that no Flexible Content layout slug, ACF field name or field storage path disappears in a non-major release without an entry in slug-migrations.json. `paths` maps a scope (field group key, then ` / layout` inside a Flexible Content layout) to the meta-key path of every field in it, as ACF builds it: enclosing group, repeater or Flexible Content names, then the field name, joined by `_`, rows written as N. CI regenerates it and fails if it is stale.',
	'layouts' => array(),
	'fields'  => array(),
	'paths'   => array(),
);

$salt_all_layouts = array();
foreach ( $GLOBALS['salt_captured_groups'] as $salt_group ) {
	$salt_names = array();
	salt_collect_slugs( $salt_group['fields'] ?? array(), $salt_names, $salt_all_layouts );
	sort( $salt_names );
	$salt_registry['fields'][ (string) ( $salt_group['key'] ?? 'unknown' ) ] = array_values( array_unique( $salt_names ) );
	salt_collect_paths( $salt_group['fields'] ?? array(), '', (string) ( $salt_group['key'] ?? 'unknown' ), $salt_registry['paths'] );
}
sort( $salt_all_layouts );
$salt_registry['layouts'] = array_values( array_unique( $salt_all_layouts ) );
ksort( $salt_registry['fields'] );
foreach ( $salt_registry['paths'] as $salt_scope => $salt_scope_paths ) {
	sort( $salt_scope_paths );
	$salt_registry['paths'][ $salt_scope ] = array_values( array_unique( $salt_scope_paths ) );
}
ksort( $salt_registry['paths'] );

$salt_json = json_encode( $salt_registry, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES );
$salt_json = str_replace( '    ', "\t", (string) $salt_json ) . "\n";

$salt_registry_path = $salt_root . '/docs/contracts/slug-registry.json';
$salt_mode          = $argv[1] ?? '--check';

if ( '--write' === $salt_mode ) {
	file_put_contents( $salt_registry_path, $salt_json );
	fwrite( STDOUT, "Registry written: {$salt_registry_path}\n" );
	exit( 0 );
}

$salt_committed = (string) file_get_contents( $salt_registry_path );
if ( $salt_committed !== $salt_json ) {
	fwrite( STDERR, "STALE REGISTRY: docs/contracts/slug-registry.json does not match the field code.\n" );
	fwrite( STDERR, "Run `php bin/extract-slugs.php --write` and commit the result.\n" );
	exit( 1 );
}
fwrite( STDOUT, "Slug registry is current.\n" );
exit( 0 );
