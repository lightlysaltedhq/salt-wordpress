// ID-3971: exercise the actual edit form, then check storage in a separate PHP process.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const ids = JSON.parse(readFileSync(`${process.env.SALT_HARNESS_STATE}.limits`));
const url = process.env.SALT_HARNESS_URL;
const browser = await chromium.launch();
try {
	const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
	const meta = (type) => JSON.parse(execFileSync(process.env.SALT_HARNESS_PHP_BIN, [fileURLToPath(new URL('./php/meta.php', import.meta.url)), ids[type].toString()]));
	const edit = (type) => page.goto(`${url}/wp-admin/post.php?post=${ids[type]}&action=edit`);
	const field = (name) => page.locator(`[data-key="field_salt_${name}"]:visible`).first();
	const save = (button) => Promise.all([page.waitForURL(/[?&]message=\d+/), page.click(button)]);
	const shot = async (locator, name) => {
		const dir = process.env.SALT_HARNESS_SCREENSHOTS;
		if (dir) {
			mkdirSync(dir, { recursive: true });
			await locator.screenshot({ path: join(dir, `${name}.png`) });
		}
	};
	await page.goto(`${url}/wp-login.php`);
	await page.fill('#user_login', 'admin');
	await page.fill('#user_pass', process.env.SALT_HARNESS_ADMIN_PASS);
	await Promise.all([page.waitForURL(/wp-admin/), page.click('#wp-submit')]);
	await edit('testimonial');
	const role = field('collection_testimonials_role');
	const roleText = 'Community gardens and landscape design consultant for accessible public spaces 🌱🌱🌱';
	const length = [...roleText].length;
	assert.ok(length > 80);
	await role.locator('input').focus();
	await page.evaluate((value) => navigator.clipboard.writeText(value), roleText);
	await page.keyboard.press('ControlOrMeta+v');
	assert.equal(await role.locator('.salt-character-count__number').textContent(), `${length} / 80`);
	assert.equal(await role.locator('input').getAttribute('maxlength'), null);
	await shot(role, 'testimonial-role-over-target');
	const rating = field('collection_testimonials_rating').locator('input');
	await field('collection_testimonials_quote').locator('textarea').fill('Our public gardens are more welcoming.');
	await rating.fill('6');
	await save('#save-post');
	assert.equal(meta('testimonial').status, 'draft');
	assert.equal(meta('testimonial').meta.rating, '6');
	assert.equal(meta('testimonial').meta.role, roleText);
	console.log('PASS invalid draft saves the out-of-range rating and all over-target text');
	await page.click('#publish');
	await field('collection_testimonials_rating').locator('.acf-error-message').waitFor();
	assert.equal(meta('testimonial').status, 'draft');
	await shot(field('collection_testimonials_rating'), 'rating-publish-refusal');
	await rating.fill('4.5');
	await save('#publish');
	assert.equal(meta('testimonial').status, 'publish');
	assert.equal(meta('testimonial').meta.rating, '4.5');
	assert.equal(meta('testimonial').meta.role, roleText);
	console.log('PASS invalid publish refused; valid half-step publishes with the full over-target role');
	await edit('service');
	assert.equal(await field('collection_services_related_services').locator('.salt-character-count__number').textContent(), '7 / 6');
	const benefits = field('collection_services_benefits');
	const listCount = benefits.locator('.salt-character-count__number').first();
	assert.equal(await listCount.textContent(), '13 / 12');
	await shot(benefits.locator('.salt-character-count').first(), 'benefits-over-target');
	await benefits.locator('[data-event="add-row"]').last().click();
	assert.equal(await listCount.textContent(), '14 / 12');
	console.log('PASS soft list counts stored and newly appended rows, not the clone');
	const render = await page.goto(ids.serviceUrl);
	assert.equal(render.status(), 200, ids.serviceUrl);
	assert.equal(await page.locator('.salt-service__benefits li').count(), 13, `${page.url()}: ${await page.title()}`);
	assert.match(await page.locator('.salt-service__benefits li').last().textContent(), /workshop 13/);
	await shot(page.locator('.salt-service__benefits'), 'published-thirteen-benefits');
	await edit('work');
	assert.equal(await field('collection_case_studies_gallery').locator('.salt-character-count__number').textContent(), '25 / 24');
	console.log('PASS gallery and relationship counts include all picks; published service renders the thirteenth benefit');
	await edit('page');
	const intro = field('faq_intro');
	assert.equal(await intro.locator('.salt-character-count__number').textContent(), '301 / 300');
	await intro.locator('textarea').fill('A'.repeat(298) + '\r\n🌱');
	assert.equal(await intro.locator('.salt-character-count__number').textContent(), '300 / 300');
	await shot(intro, 'nested-intro-at-target');
	await intro.locator('textarea').press('End');
	await page.keyboard.insertText('🌱');
	assert.equal(await intro.locator('.salt-character-count__number').textContent(), '301 / 300');
	await shot(intro, 'nested-intro-over-target');
	await page.locator('[data-key="field_salt_sections_container"] a[data-name="add-layout"]:visible').last().click();
	await page.click('.acf-fc-popup a[data-layout="features"]');
	const appended = field('features_intro');
	await appended.locator('textarea').fill('An introduction to the service.');
	assert.equal(await appended.locator('.salt-character-count__number').textContent(), '31 / 300');
	await shot(appended, 'appended-section-count');
	console.log('PASS nested and appended layouts count code points and CRLF through the boundary');
	await edit('location');
	const hours = field('collection_locations_hours');
	await hours.locator('[data-event="add-row"]').last().click();
	const open = field('collection_locations_hours_open');
	await open.locator('input[type=text]').fill('25:15');
	await save('#save-post');
	assert.equal(meta('location').meta.hours_0_open, '25:15');
	assert.equal(await open.locator('input[type=text]').inputValue(), '25:15');
	await page.click('#publish');
	await open.locator('.acf-error-message').waitFor();
	assert.equal(meta('location').status, 'draft');
	await shot(open, 'invalid-time-on-publish');
	await open.locator('input[type=text]').fill('23:59');
	await save('#publish');
	assert.equal(meta('location').status, 'publish');
	console.log('PASS invalid HH:MM round-trips on draft, refuses publication and recovers at 23:59');
	await edit('mismatch');
	await save('#save-post');
	assert.equal(meta('mismatch').status, 'draft');
	await page.click('#publish');
	const picker = field('collection_showcase_query_categories');
	await picker.locator('.acf-error-message').waitFor();
	assert.match(await picker.textContent(), /belonging to the selected collection/);
	assert.equal(meta('mismatch').status, 'draft');
	await shot(picker, 'cross-source-topic-refusal');
	console.log('PASS a stale post category in a services query saves as a draft but refuses publication');
	await page.goto(`${url}/wp-admin/user-edit.php?user_id=${ids.user}`);
	const tick = page.locator('[data-key="field_salt_collection_team_show_on_website"] input[type=checkbox]');
	const profileCount = page.locator('#salt-character-count-display_name');
	assert.equal(await profileCount.isVisible(), false);
	await tick.check({force: true});
	await page.selectOption('#display_name', 'L'.repeat(65));
	assert.equal(await profileCount.getAttribute('data-mark'), '60');
	await shot(page.locator('.user-display-name-wrap'), 'profile-search-note');
	await page.selectOption('#display_name', `${'L'.repeat(65)} ${'M'.repeat(65)}`);
	assert.equal(await profileCount.getAttribute('data-mark'), '120');
	await shot(page.locator('.user-display-name-wrap'), 'profile-over-target');
	await tick.uncheck({force: true});
	assert.equal(await profileCount.isVisible(), false);
	console.log('PASS ticked user profile shows both display-name notes; unticking hides the count');
} finally {
	await browser.close();
}
